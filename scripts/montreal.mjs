// Builds src/montreal.js, the Circuit Gilles-Villeneuve layout, from open data:
// the centerline GeoJSON of bacinger/f1-circuits (MIT license), traced from
// OpenStreetMap. Download it, then run this script on it:
//
//   curl -LO https://raw.githubusercontent.com/bacinger/f1-circuits/master/circuits/ca-1978.geojson
//   node scripts/montreal.mjs ca-1978.geojson
//
// Coordinates are projected to meters around the track's center: x east,
// z south (north is -z, so the map isn't mirrored). The line is resampled every
// STEP meters and lightly smoothed, so the spline doesn't overshoot where long
// straights meet closely spaced corner points.
import { readFileSync, writeFileSync } from 'node:fs';

const STEP = 6;     // m between control points
const SMOOTH = 2;   // [1/4, 1/2, 1/4] passes

const geo = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const feature = geo.features[0];
let ll = feature.geometry.coordinates;
const same = (a, b) => a[0] === b[0] && a[1] === b[1];
if (same(ll[0], ll[ll.length - 1])) ll = ll.slice(0, -1);

const lat0 = ll.reduce((s, p) => s + p[1], 0) / ll.length, lon0 = ll.reduce((s, p) => s + p[0], 0) / ll.length;
const R = 6371008.8, rad = Math.PI / 180, k = Math.cos(lat0 * rad);
const pts = ll.map(([lon, lat]) => [(lon - lon0) * rad * R * k, -(lat - lat0) * rad * R]);

// Resample the closed polyline at even steps.
const n = pts.length, seg = pts.map((a, i) => Math.hypot(pts[(i + 1) % n][0] - a[0], pts[(i + 1) % n][1] - a[1]));
const length = seg.reduce((s, v) => s + v, 0), count = Math.round(length / STEP);
let out = [];
for (let j = 0, i = 0, base = 0; j < count; j++) {
  const d = (j * length) / count;
  while (base + seg[i] < d) base += seg[i++];
  const a = pts[i], b = pts[(i + 1) % n], t = (d - base) / seg[i];
  out.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]);
}
for (let p = 0; p < SMOOTH; p++) {
  out = out.map((q, i) => {
    const a = out[(i - 1 + count) % count], b = out[(i + 1) % count];
    return [0.25 * a[0] + 0.5 * q[0] + 0.25 * b[0], 0.25 * a[1] + 0.5 * q[1] + 0.25 * b[1]];
  });
}

const r1 = (v) => Math.round(v * 10) / 10;
const { Name, length: official } = feature.properties;
writeFileSync(new URL('../src/montreal.js', import.meta.url), `// Generated by scripts/montreal.mjs from open data: ${Name}, Montreal
// (Île Notre-Dame), centerline from github.com/bacinger/f1-circuits (MIT
// license, traced from OpenStreetMap). Meters around ${lat0.toFixed(5)}° N,
// ${(-lon0).toFixed(5)}° W: x east, z south. Official length ${official} m.
export const MONTREAL = ${JSON.stringify(out.map((p) => p.map(r1)))};
`);
console.log(`wrote src/montreal.js: ${count} points, ${length.toFixed(0)} m`);
